export function getSkillDescription(skill: Skill, language: Language): string {
  if (language !== "es") return skill.description;
  return SKILL_DESCRIPTIONS_ES[skill.id] ?? skill.description;
}

export function getLrPassiveDescription(creature: Creature, passive: LrPassive, language: Language): string {
  if (language !== "es") return passive.description;
  return LR_PASSIVE_DESCRIPTIONS_ES[creature.id] ?? passive.description;
}

export function getUltimateDescription(ultimate: UltimateSkill, language: Language): string {
  if (language !== "es") return ultimate.description;
  return ULTIMATE_DESCRIPTIONS_ES[ultimate.id] ?? ultimate.description;
}
